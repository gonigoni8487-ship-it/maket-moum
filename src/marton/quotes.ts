export const quoteSource = (q: Quote) => `— ${q.who}${q.book ? `, ${q.book}` : ''}`;

/** 오늘(매장 날짜 기준)의 명언 5장 */
export function todaysQuotes(dayIndex: number, count = 5): Quote[] {
  const start = ((dayIndex * count) % QUOTES.length + QUOTES.length) % QUOTES.length;
  return Array.from({ length: count }, (_, i) => QUOTES[(start + i) % QUOTES.length]);
}
